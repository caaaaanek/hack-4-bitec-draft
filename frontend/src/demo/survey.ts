export type TokenState = 'valid' | 'used' | 'invalid'

/** Мок жетонів: demo це чинний, used це вже використаний, решта недійсні. */
export function checkToken(token: string | undefined): TokenState {
  if (token === 'demo') return 'valid'
  if (token === 'used') return 'used'
  return 'invalid'
}
