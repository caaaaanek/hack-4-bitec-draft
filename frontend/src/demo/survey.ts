/** Синтетична демо-анкета й мок жетонів. Без вільного тексту. */
import type { ComponentId } from '@/lib/scoring/methodology'

export interface SurveyOption {
  id: string
  text: string
  /** Рівень зрілості 1-5, якому відповідає варіант. */
  level: 1 | 2 | 3 | 4 | 5
}
export interface SurveyQuestion {
  id: string
  text: string
  options: SurveyOption[]
}
export interface SurveySection {
  id: ComponentId
  title: string
  /** Про що розділ, одним виразом після «N питання»: «про ставлення до доброчесності». */
  about: string
  questions: SurveyQuestion[]
}
export interface Survey {
  id: string
  title: string
  category: string
  sections: SurveySection[]
}

const q = (
  id: string,
  text: string,
  opts: [string, string, string, string, string],
): SurveyQuestion => ({
  id,
  text,
  options: opts.map((t, i) => ({
    id: `${id}-o${i + 1}`,
    text: t,
    level: (i + 1) as SurveyOption['level'],
  })),
})

